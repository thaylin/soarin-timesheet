-- =====================================================================================
-- V1__init.sql - initial schema for the Soarin shop time log.
--
-- HOW MIGRATIONS WORK (Flyway)
--   * Flyway runs every file in this folder, in version order, the first time the app
--     starts against a database that hasn't seen it yet, and records it in the
--     "flyway_schema_history" table.
--   * NEVER edit a migration that has already been released/run on the Pi. Flyway stores
--     a checksum and will refuse to start if an old file changes. To change the schema,
--     add a NEW file: V2__describe_the_change.sql, V3__..., and so on.
--   * The Java entity classes (Student, TimeEntry) must match these tables. On startup
--     Hibernate validates this ("spring.jpa.hibernate.ddl-auto=validate") and fails fast
--     if they drift apart.
--
-- TIME ZONES
--   Every timestamp column is TIMESTAMPTZ ("timestamp with time zone"). PostgreSQL stores
--   these as an exact instant in UTC, so there is no ambiguity around daylight saving time
--   (e.g. the repeated 1:00-2:00 AM hour in November). The app converts to
--   America/New_York only when it needs to know the local shop day.
-- =====================================================================================


-- -------------------------------------------------------------------------------------
-- student: the team roster. This is an education record under FERPA - keep it minimal.
-- Students are deactivated (active = false), not deleted, so their time history stays.
-- Future columns (e.g. a profile picture path, group/subteam) can be added in new migrations.
-- -------------------------------------------------------------------------------------
CREATE TABLE student (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- The school ID printed on the badge barcode. Stored trimmed and UPPER-CASE
    -- (the app normalizes before saving and before looking up).
    student_number   VARCHAR(32)  NOT NULL,
    first_name       VARCHAR(100) NOT NULL,
    last_name        VARCHAR(100) NOT NULL,
    graduation_year  INTEGER,
    active           BOOLEAN      NOT NULL DEFAULT TRUE,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),

    CONSTRAINT uq_student_number UNIQUE (student_number),
    CONSTRAINT ck_student_number_format CHECK (student_number ~ '^[A-Z0-9-]{1,32}$')
);


-- -------------------------------------------------------------------------------------
-- time_entry: one stretch of shop time. A sign-in scan creates a row with
-- signed_out_at = NULL ("open"); the matching sign-out scan fills signed_out_at in.
-- This is a TIME LOG, not a login/session table.
-- -------------------------------------------------------------------------------------
CREATE TABLE time_entry (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- ON DELETE RESTRICT: you cannot delete a student who has time history (deactivate instead).
    student_id     BIGINT       NOT NULL REFERENCES student (id) ON DELETE RESTRICT,
    signed_in_at   TIMESTAMPTZ  NOT NULL,
    signed_out_at  TIMESTAMPTZ,
    -- Why the entry was closed: SCAN (student scanned out), AUTO_MIDNIGHT (closed by the
    -- end-of-day job), MANUAL (reserved for admin corrections). NULL while open.
    close_reason   VARCHAR(20),
    -- TRUE when an admin should look at this entry (e.g. it was auto-closed at midnight,
    -- so the real sign-out time is unknown).
    needs_review   BOOLEAN      NOT NULL DEFAULT FALSE,
    -- Optimistic-locking counter used by Hibernate (@Version). Don't update it by hand.
    version        INTEGER      NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- An entry is closed if and only if it has a close reason.
    CONSTRAINT ck_time_entry_close_consistent CHECK ((signed_out_at IS NULL) = (close_reason IS NULL)),
    CONSTRAINT ck_time_entry_out_after_in     CHECK (signed_out_at IS NULL OR signed_out_at >= signed_in_at),
    CONSTRAINT ck_time_entry_close_reason     CHECK (close_reason IN ('SCAN', 'AUTO_MIDNIGHT', 'MANUAL'))
);

-- A student can have at most ONE open entry. This is the database-level safety net behind
-- the toggle logic: even with a bug or a race, two open entries can never be stored.
-- ("Partial" index: it only covers rows WHERE signed_out_at IS NULL.)
CREATE UNIQUE INDEX uq_time_entry_one_open_per_student
    ON time_entry (student_id)
    WHERE signed_out_at IS NULL;

-- Speeds up "latest entry for this student" and "entries for this student today".
CREATE INDEX ix_time_entry_student_signed_in
    ON time_entry (student_id, signed_in_at DESC);

-- Speeds up the future admin "entries needing review" list.
CREATE INDEX ix_time_entry_needs_review
    ON time_entry (signed_in_at)
    WHERE needs_review;
